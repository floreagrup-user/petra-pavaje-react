// Builds src/data/garan-labels.ts: which GARAN guarantee label (WebP) belongs
// to which row of the product and element tables. Matches by product slug +
// row label (pavers, kerbs) or by product code (gutters, fences), and reports
// every row without a label and every label file left unused.
//
// Usage: npx tsx scripts/build-garan-labels.ts <folder with the label files>
// The WebP files themselves go to R2 under etichete-garan/<file name>.
import fs from 'node:fs'
import path from 'node:path'
import { products } from '../src/data/products'
import { elementCategories } from '../src/data/elements'
import { woodstoneCategories } from '../src/data/woodstone'

const dir = process.argv[2]
if (!dir) throw new Error('usage: npx tsx scripts/build-garan-labels.ts <label folder>')

// Woodstone reuses product codes across its categories (880047 is a paving
// slab and a palisade), so its labels are matched inside the folder named
// after the category slug, and keyed by code because the English pages
// translate the variant names.
// Gutters (rigole) have no commercial guarantee of durability, so no GARAN label.
const SKIP_FOLDERS = new Set(['rigole'])
const files = new Set<string>()
const woodstoneFiles = new Map<string, string[]>()
function walk(d: string) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name)
    if (e.isDirectory()) { if (!SKIP_FOLDERS.has(e.name)) walk(p) }
    else if (e.name.startsWith('garan-') && e.name.endsWith('.webp') && !e.name.startsWith('garan-nested')) {
      if (files.has(e.name)) throw new Error(`duplicate label file name: ${e.name}`)
      files.add(e.name)
      const rel = path.relative(dir, d).split(path.sep)
      if (rel[0] === 'woodstone-lemn-pietrificat') woodstoneFiles.set(rel[1], [...(woodstoneFiles.get(rel[1]) || []), e.name])
    }
  }
}
walk(dir)

// '20×16.5×6 fără cant' -> '20x16-5x6-fara-cant', 'MIX 7.25 (26/22×16 ...)' -> 'mix-7-25'
function key(label: string): string {
  return label
    .replace(/\(.*\)/g, '')
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/×/g, 'x')
    .replace(/[./\s,]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
}

const used = new Set<string>()
const missing: string[] = []
function pick(candidates: string[]): string | undefined {
  const hit = candidates.map((c) => `garan-${c}.webp`).find((f) => files.has(f))
  if (hit) used.add(hit)
  return hit
}

const productLabels: Record<string, Record<string, string>> = {}
for (const p of products) {
  const rows = p.dimensionsList || []
  for (const d of rows) {
    const k = key(d.label)
    const noCm = k.replace(/-cm$/, '')
    const file = pick([
      `${p.slug}-${k}`, `${p.slug}-${noCm}`, `${p.slug}-${noCm}-cm`,
      `${p.slug}-${noCm.replace(/-(tactil|parcare|acces)$/, '')}`,
      k, noCm,
      ...(rows.length === 1 ? [p.slug, `${p.slug}-dreapta`] : []),
    ])
    if (file) (productLabels[p.slug] ||= {})[d.label] = file
    else missing.push(`${p.category}/${p.slug}: "${d.label}"`)
  }
}

const elementLabels: Record<string, Record<string, string>> = {}
const WANTED = new Set(['robusto', 'modern', 'baroc'])
for (const c of elementCategories) {
  if (!WANTED.has(c.slug)) continue
  for (const g of c.variantGroups || []) {
    for (const v of g.variants) {
      const byCode = v.code && v.code !== '—' ? [...files].find((f) => f.startsWith(`garan-${v.code}-`)) : undefined
      if (byCode) used.add(byCode)
      const file = byCode || pick([`element-gard-${key(v.dimensions).replace(/-cm$/, '')}`])
      if (file) (elementLabels[c.slug] ||= {})[v.name] = file
      else missing.push(`element/${c.slug}: "${v.name}" (${v.code})`)
    }
  }
}

const woodstoneLabels: Record<string, Record<string, string>> = {}
for (const c of woodstoneCategories) {
  const inFolder = woodstoneFiles.get(c.slug) || []
  for (const g of c.variantGroups || []) {
    for (const v of g.variants) {
      const hits = inFolder.filter((f) => f.startsWith(`garan-${v.code}-`))
      if (hits.length === 1) {
        used.add(hits[0])
        ;(woodstoneLabels[c.slug] ||= {})[v.code] = hits[0]
      } else missing.push(`woodstone/${c.slug}: "${v.name}" (${v.code}) -> ${hits.length} files`)
    }
  }
}

const unused = [...files].filter((f) => !used.has(f)).sort()
const out = `// Generated by scripts/build-garan-labels.ts - do not edit by hand.
// GARAN guarantee label file (R2 key etichete-garan/<file>) per table row:
// product slug -> dimensionsList label, element category slug -> variant name,
// Woodstone category slug -> product code.

export const GARAN_PRODUCT_LABELS: Record<string, Record<string, string>> = ${JSON.stringify(productLabels, null, 2)}

export const GARAN_ELEMENT_LABELS: Record<string, Record<string, string>> = ${JSON.stringify(elementLabels, null, 2)}

// Woodstone: category slug -> product code
export const GARAN_WOODSTONE_LABELS: Record<string, Record<string, string>> = ${JSON.stringify(woodstoneLabels, null, 2)}
`
fs.writeFileSync(path.join(import.meta.dirname, '../src/data/garan-labels.ts'), out)

const count = (o: Record<string, Record<string, string>>) => Object.values(o).reduce((n, r) => n + Object.keys(r).length, 0)
console.log(`label files: ${files.size}, product rows matched: ${count(productLabels)}, element rows matched: ${count(elementLabels)}, woodstone rows matched: ${count(woodstoneLabels)}`)
console.log(`rows without a label (${missing.length}):\n  ${missing.join('\n  ')}`)
console.log(`label files not used (${unused.length}):\n  ${unused.join('\n  ')}`)
